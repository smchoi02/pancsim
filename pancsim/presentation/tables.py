def sheet(code, title, header, rows, widths, takeaway, note, fig, base_rows=()):
    ws = wb.create_sheet(code)
    ws["A1"] = f"{code}. {title}"; ws["A1"].font = Font(name=FONT, size=14, bold=True)
    ws["A2"] = takeaway; ws["A2"].font = Font(name=FONT, size=11, color="2A78D6", bold=True)
    r0 = 4
    for j, h in enumerate(header, 1):
        c = ws.cell(r0, j, h); c.font = Font(name=FONT, bold=True, color="FFFFFF", size=10.5); c.fill = HFILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True); c.border = BORDER
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(r0 + i, j, v); c.font = Font(name=FONT, size=10.5, bold=(i - 1) in base_rows)
            c.alignment = Alignment(horizontal="left" if j == 1 else "right", vertical="center", wrap_text=True); c.border = BORDER
            if (i - 1) in base_rows:
                c.fill = BFILL
    ws.row_dimensions[r0].height = 34
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    rn = r0 + len(rows) + 2
    for k, n in enumerate(note if isinstance(note, list) else [note]):
        ws.cell(rn + k, 1, n).font = Font(name=FONT, size=9.5, color="52514E")
    ws.cell(rn + len(note if isinstance(note, list) else [note]) + 1, 1, f"그림 파일: {fig}").font = Font(name=FONT, size=9.5, color="8A8984")
    ws.sheet_view.showGridLines = False
    index.append((code, title, fig, takeaway))


